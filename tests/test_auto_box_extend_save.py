"""自動拡張ページの次ページ自動保存を、app.js の実関数を Node.js で実行して検証する。

static/app.js から必要な関数だけを取り出し、state と UI/通信をスタブにして動かす。
"""

import json
import subprocess
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[1]

HARNESS = r"""
const fs = require('fs');
const vm = require('vm');
const src = fs.readFileSync('static/app.js', 'utf8');

function extract(name) {
  const start = src.search(new RegExp('^(async )?function ' + name + '\\(', 'm'));
  if (start < 0) throw new Error('function not found: ' + name);
  let i = src.indexOf(') {', start) + 2;
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') {
      depth--;
      if (depth === 0) return src.slice(start, i + 1);
    }
  }
  throw new Error('unterminated function: ' + name);
}

function load(names, globals) {
  const ctx = vm.createContext(Object.assign({ console, setTimeout }, globals));
  vm.runInContext(names.map(extract).join('\n'), ctx);
  return ctx;
}

const tick = () => new Promise((resolve) => setTimeout(resolve, 20));

function baseState(overrides) {
  return Object.assign({
    bookId: 'b',
    pageId: 'p1',
    pages: ['p1', 'p2'],
    isNavigating: false,
    characters: [{ char_id: 'C1' }, { char_id: 'C2' }, { char_id: 'C3' }],
    columns: [[0, 1], [2]],
    columnIds: ['COL0001', 'COL0002'],
    columnBoxes: [
      { x: 1, y: 1, width: 10, height: 10 },
      { x: 20, y: 1, width: 10, height: 10 },
    ],
    wariByChar: [],
    segments: [[0, 1]],
    segmentIds: ['SEG0001'],
    isDirty: true,
    isSegmentsDirty: false,
    hasOriginalAnnotations: true,
    hasCustomSegmentIds: false,
    predictionMeta: null,
    autoBoxExtended: true,
    hasUserEdited: false,
    initialAutoGenerated: false,
  }, overrides);
}

function candidate(overrides) {
  const state = baseState(overrides);
  const ctx = load(['hasUnassignedCharacters', 'isAutoBoxExtendSaveCandidate'], { state });
  return ctx.isAutoBoxExtendSaveCandidate();
}

async function navigateForward(overrides) {
  const state = baseState(overrides);
  const log = { dialogCalls: 0, loaded: [], fetchCalls: [], toasts: [] };
  const globals = {
    state,
    elements: { pageSelect: { value: '' } },
    window: { alert: (message) => log.toasts.push('alert:' + message) },
    fetch: async (url, init) => {
      log.fetchCalls.push({ url, body: JSON.parse(init.body) });
      return { ok: true, json: async () => ({ success: true, message: 'ok' }) };
    },
    showToast: (message) => log.toasts.push(message),
    showLoading: () => {},
    showSaveDialog: async () => { log.dialogCalls += 1; return 'cancel'; },
    loadPageData: async (_bookId, pageId) => { log.loaded.push(pageId); },
    buildColumnPredictionFeedbackFrom: () => null,
    buildSegmentPredictionFeedbackFrom: () => null,
    applySnapshotSaveSuccess: () => {},
    updatePageSaveStatus: () => {},
    updateBookProgress: () => {},
    scheduleModelStatusRefresh: () => {},
  };
  const ctx = load([
    'navigatePage', 'isInitialAutoSaveCandidate', 'isAutoBoxExtendSaveCandidate',
    'hasUnassignedCharacters', 'createSaveSnapshot', 'cloneForSave',
    'renumberSnapshotSegmentIdsIfAuto', 'getUnassignedCount',
    'validateColumnSaveSnapshot', 'validateSegmentSaveSnapshot',
    'buildSegmentsPayload', 'buildWariPayload', 'saveSnapshot',
    'startBackgroundSave', 'getSaveSnapshotValidationError',
    'showSaveValidationError', 'startValidatedBackgroundSave',
  ], globals);
  await ctx.navigatePage(1);
  await tick();
  return log;
}
"""


def _run_node(body: str) -> Any:
    result = subprocess.run(
        ["node", "-"],
        input=HARNESS + body,
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


def _candidate(**overrides: object) -> bool:
    return _run_node(f"console.log(JSON.stringify(candidate({json.dumps(overrides)})));")


def _navigate_forward(**overrides: object) -> dict[str, Any]:
    return _run_node(
        f"navigateForward({json.dumps(overrides)}).then((log) => console.log(JSON.stringify(log)));"
    )


# ===== isAutoBoxExtendSaveCandidate =====
def test_candidate_with_original_annotations_ignores_load_derived_segments_dirty() -> None:
    # 保存済みの列があるページの isSegmentsDirty は読み込み由来なので、候補から外さない
    assert _candidate(hasOriginalAnnotations=True, isSegmentsDirty=True) is True


def test_candidate_without_original_annotations_excludes_segments_dirty() -> None:
    # 自動生成ページのヒューリスティックなセグメント推定は、確認なしで保存しない
    assert _candidate(hasOriginalAnnotations=False, isSegmentsDirty=True) is False


def test_candidate_excludes_user_edited_page_even_with_original_annotations() -> None:
    assert _candidate(hasOriginalAnnotations=True, isSegmentsDirty=True, hasUserEdited=True) is False
    assert _candidate(hasOriginalAnnotations=True, isSegmentsDirty=False, hasUserEdited=True) is False


@pytest.mark.parametrize("has_original", [True, False])
def test_candidate_without_segments_dirty(has_original: bool) -> None:
    assert _candidate(hasOriginalAnnotations=has_original, isSegmentsDirty=False) is True


@pytest.mark.parametrize(
    "overrides",
    [
        {"autoBoxExtended": False},
        {"isDirty": False},
        {"columns": []},
        {"columns": [[0, 1]]},  # 文字 C3 が未割当
    ],
)
def test_candidate_keeps_other_conditions(overrides: dict[str, object]) -> None:
    assert _candidate(hasOriginalAnnotations=True, isSegmentsDirty=True, **overrides) is False


# ===== navigatePage（保存ダイアログと自動保存の内容） =====
def test_navigate_auto_saves_columns_and_segments_without_dialog() -> None:
    log = _navigate_forward(hasOriginalAnnotations=True, isSegmentsDirty=True)

    assert log["dialogCalls"] == 0
    assert log["loaded"] == ["p2"]
    # 列 → セグメントの順に保存され、セグメントにも列IDが入る
    assert [call["url"] for call in log["fetchCalls"]] == [
        "/api/books/b/pages/p1/save",
        "/api/books/b/pages/p1/save_segments",
    ]
    columns_body = log["fetchCalls"][0]["body"]
    assert [column["char_ids"] for column in columns_body["columns"]] == [["C1", "C2"], ["C3"]]
    assert all("box" in column for column in columns_body["columns"])
    assert log["fetchCalls"][1]["body"]["segments"] == [
        {"segment_id": "SEG0001", "column_ids": ["COL0001", "COL0002"]}
    ]
    assert "保存完了: p1" in log["toasts"]


def test_navigate_without_segments_dirty_saves_columns_only() -> None:
    log = _navigate_forward(hasOriginalAnnotations=True, isSegmentsDirty=False)

    assert log["dialogCalls"] == 0
    assert [call["url"] for call in log["fetchCalls"]] == ["/api/books/b/pages/p1/save"]


def test_navigate_shows_dialog_for_generated_page_with_segments_dirty() -> None:
    log = _navigate_forward(hasOriginalAnnotations=False, isSegmentsDirty=True)

    assert log["dialogCalls"] == 1
    assert log["fetchCalls"] == []
    assert log["loaded"] == []


def test_navigate_shows_dialog_after_user_edit() -> None:
    log = _navigate_forward(hasOriginalAnnotations=True, isSegmentsDirty=True, hasUserEdited=True)

    assert log["dialogCalls"] == 1
    assert log["fetchCalls"] == []
    assert log["loaded"] == []
